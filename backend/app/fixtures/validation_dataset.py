"""
Empirical Validation Ground Truth Dataset for BidVerify AI
Comprehensive, non-sensitive test cases defining manual ground truth across
OCR, classification, structured field extraction, compliance verification,
RAG retrieval, duplicate detection, and manual verification baselines.
"""

from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field


class GroundTruthTestCase(BaseModel):
    """
    Ground truth specification for a single benchmark evaluation case.
    """
    id: str
    title: str
    category: str  # GST, PAN, UDYAM, FINANCIAL, OEM, LOCAL_CONTENT, QUALITY, CROSS_DOC, DUPLICATE, COMPLIANCE, RAG, DEBARMENT
    document_type: str
    quality_level: str = "GOOD"  # GOOD, ACCEPTABLE, POOR, UNUSABLE

    # Synthetic document payload / simulated text / scanned features
    sample_text: str
    sample_filename: str = "sample_document.pdf"
    file_size_bytes: int = 45000

    # Ground Truth Expectation
    expected_doc_type: str
    expected_fields: Dict[str, Any] = Field(default_factory=dict)
    expected_ocr_keywords: List[str] = Field(default_factory=list)
    expected_compliance_status: str = "PASS"  # PASS, FAIL, REVIEW_REQUIRED, NOT_APPLICABLE
    expected_compliance_is_met: Optional[bool] = True

    # RAG Ground Truth
    rag_query: Optional[str] = None
    expected_rag_clause: Optional[str] = None
    expected_rag_section: Optional[str] = None

    # Duplicate Expectation
    is_duplicate: bool = False
    duplicate_of_id: Optional[str] = None

    # Realistic manual verification time baseline in seconds (e.g. human officer verification)
    manual_baseline_sec: float = 300.0  # 5 minutes default per document/clause verification


